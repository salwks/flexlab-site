const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');
new vm.Script(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
const queue=html.slice(html.indexOf('const thumbQueue='),html.indexOf('const thumbObserver='));
const ctx=vm.createContext({});vm.runInContext(queue,ctx);
const img={dataset:{fallback:'proxy'},isConnected:true,style:{},parentElement:{classList:{add(){}}}};
ctx.img=img;
vm.runInContext("queueThumb(img,'broken-direct')",ctx);
assert.equal(img.src,'broken-direct');
img.onerror();assert.equal(img.src,'proxy','fallback must be dispatched after the direct image fails');
img.onerror();assert.equal(img.style.display,'none','fallback failure must terminate');
assert.equal(vm.runInContext('thumbActive',ctx),0);
const images=Array.from({length:7},()=>({dataset:{},isConnected:true,style:{}}));ctx.images=images;
vm.runInContext("images.forEach((img,i)=>queueThumb(img,'url'+i))",ctx);
assert.equal(images.filter(i=>i.src).length,4);
images[0].onload();assert.equal(images[4].src,'url4');
images[5].isConnected=false;images[1].onload();assert.equal(images[6].src,'url6');
console.log('PASS: script syntax, fallback dispatch/termination, concurrency limit, detached cards');
